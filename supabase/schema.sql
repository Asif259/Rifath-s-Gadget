-- 1. Enable required extensions
create extension if not exists "uuid-ossp";

-- 2. Admin Users Table
-- Stores authorized admin users linked to auth.users
create table if not exists public.admin_users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  created_at timestamptz not null default timezone('utc'::text, now())
);

comment on table public.admin_users is 'Authorized admin accounts for dashboard access.';

-- 3. Deliveries Table
-- Stores dynamic delivery records replacing the static content.ts array
create table if not exists public.deliveries (
  id bigint generated by default as identity primary key,
  model text not null,
  buyer_name_bn text not null,
  buyer_name_en text not null,
  saving integer not null check (saving >= 0),
  highlights text[] not null default '{}',
  specs jsonb not null default '[]'::jsonb, -- Array of { "bn": string, "en": string }
  asked_bn text,
  asked_en text,
  review_name text,
  review_text_bn text,
  review_text_en text,
  review_translated boolean default false,

  -- Photos: Array of { "url": string, "thumb_url": string, "sort_order": number, "is_cover": boolean, "storage_path"?: string, "thumb_path"?: string }
  photos jsonb not null default '[]'::jsonb,

  -- Flags & curation
  is_hero boolean not null default false,
  is_featured boolean not null default false,
  is_published boolean not null default true,
  sort_order integer not null default 0,

  -- Timestamps
  created_at timestamptz not null default timezone('utc'::text, now()),
  updated_at timestamptz not null default timezone('utc'::text, now())
);

comment on table public.deliveries is 'Laptop sourcing deliveries, verified buyer stories, and specs.';

-- 4. Automatic updated_at Trigger
create or replace function public.handle_updated_at()
returns trigger as $$
begin
  new.updated_at = timezone('utc'::text, now());
  return new;
end;
$$ language plpgsql;

drop trigger if exists set_deliveries_updated_at on public.deliveries;
create trigger set_deliveries_updated_at
  before update on public.deliveries
  for each row
  execute function public.handle_updated_at();

-- 5. Performance Indexes
create index if not exists idx_deliveries_published_sort on public.deliveries (is_published, sort_order desc, id desc);
create index if not exists idx_deliveries_hero on public.deliveries (is_hero) where is_published = true;
create index if not exists idx_deliveries_featured on public.deliveries (is_featured) where is_published = true;

-- 6. Row Level Security (RLS) & Table Grants
alter table public.admin_users enable row level security;
alter table public.deliveries enable row level security;

-- Grant API roles access to tables (RLS will filter which specific rows they can read/write)
grant usage on schema public to anon, authenticated;
grant select on table public.deliveries to anon, authenticated;
grant insert, update, delete on table public.deliveries to authenticated;
grant select on table public.admin_users to authenticated;

-- Admin Users Policies
drop policy if exists "Allow admins to select their own admin record" on public.admin_users;
create policy "Allow admins to select their own admin record"
  on public.admin_users
  for select
  to authenticated
  using (id = (select auth.uid()));

-- Deliveries Policies
-- Public: view published deliveries only
drop policy if exists "Allow public read on published deliveries" on public.deliveries;
create policy "Allow public read on published deliveries"
  on public.deliveries
  for select
  to anon, authenticated
  using (is_published = true);

-- Admin: view all deliveries (including drafts/unpublished)
drop policy if exists "Allow admins to select all deliveries" on public.deliveries;
create policy "Allow admins to select all deliveries"
  on public.deliveries
  for select
  to authenticated
  using (exists (select 1 from public.admin_users where admin_users.id = (select auth.uid())));

-- Admin: insert deliveries
drop policy if exists "Allow admins to insert deliveries" on public.deliveries;
create policy "Allow admins to insert deliveries"
  on public.deliveries
  for insert
  to authenticated
  with check (exists (select 1 from public.admin_users where admin_users.id = (select auth.uid())));

-- Admin: update deliveries
drop policy if exists "Allow admins to update deliveries" on public.deliveries;
create policy "Allow admins to update deliveries"
  on public.deliveries
  for update
  to authenticated
  using (exists (select 1 from public.admin_users where admin_users.id = (select auth.uid())))
  with check (exists (select 1 from public.admin_users where admin_users.id = (select auth.uid())));

-- Admin: delete deliveries
drop policy if exists "Allow admins to delete deliveries" on public.deliveries;
create policy "Allow admins to delete deliveries"
  on public.deliveries
  for delete
  to authenticated
  using (exists (select 1 from public.admin_users where admin_users.id = (select auth.uid())));

-- 7. Supabase Storage: delivery-photos Bucket Setup & Policies
insert into storage.buckets (id, name, public)
values ('delivery-photos', 'delivery-photos', true)
on conflict (id) do update set public = true;

-- Storage: public can view all photos
drop policy if exists "Allow public read on delivery photos" on storage.objects;
create policy "Allow public read on delivery photos"
  on storage.objects
  for select
  using (bucket_id = 'delivery-photos');

-- Storage: admins can upload photos
drop policy if exists "Allow admins to upload delivery photos" on storage.objects;
create policy "Allow admins to upload delivery photos"
  on storage.objects
  for insert
  to authenticated
  with check (
    bucket_id = 'delivery-photos'
    and exists (select 1 from public.admin_users where admin_users.id = (select auth.uid()))
  );

-- Storage: admins can update/upsert photos
drop policy if exists "Allow admins to update delivery photos" on storage.objects;
create policy "Allow admins to update delivery photos"
  on storage.objects
  for update
  to authenticated
  using (
    bucket_id = 'delivery-photos'
    and exists (select 1 from public.admin_users where admin_users.id = (select auth.uid()))
  )
  with check (
    bucket_id = 'delivery-photos'
    and exists (select 1 from public.admin_users where admin_users.id = (select auth.uid()))
  );

-- Storage: admins can delete photos
drop policy if exists "Allow admins to delete delivery photos" on storage.objects;
create policy "Allow admins to delete delivery photos"
  on storage.objects
  for delete
  to authenticated
  using (
    bucket_id = 'delivery-photos'
    and exists (select 1 from public.admin_users where admin_users.id = (select auth.uid()))
  );

